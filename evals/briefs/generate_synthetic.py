# ----------------------------------------------------------------------------- утилиты


def rng_for(brief_id: str) -> np.random.Generator:
    """Производный сид: SEED + стабильный хеш id брифа (не зависит от PYTHONHASHSEED)."""
    offset = int(hashlib.sha256(brief_id.encode("utf-8")).hexdigest()[:8], 16)
    return np.random.default_rng(SEED + offset)


def ru_int(n: float) -> str:
    return f"{round(n):,}".replace(",", " ")


def ru_num(x: float, nd: int = 1) -> str:
    return f"{x:.{nd}f}".replace(".", ",")


def ru_pct(x: float, nd: int = 1) -> str:
    return ru_num(x * 100, nd) + "%"


def _q(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _header_lines(title: str, kind: str, publisher: str, published: str, note: str) -> list[str]:
    return [
        f"title: {_q(title)}",
        f"kind: {kind}",
        "synthetic: true",
        "source_url: null",
        f"publisher: {_q(publisher)}",
        f"published: {published}",
        f"retrieved: {RETRIEVED}",
        f"note: {_q(note)}",
        f"generator: {_q(GENERATOR)}",
    ]


def front_matter(title: str, kind: str, publisher: str, published: str, note: str) -> str:
    return "\n".join(["---", *_header_lines(title, kind, publisher, published, note), "---", ""]) + "\n"


def meta_yaml(
    title: str,
    kind: str,
    publisher: str,
    published: str,
    note: str,
    seed_of: str,
    columns: dict[str, str] | None = None,
) -> str:
    lines = _header_lines(title, kind, publisher, published, note)
    offset = int(hashlib.sha256(seed_of.encode("utf-8")).hexdigest()[:8], 16)
    lines.append(f"seed: {SEED + offset}")
    if columns:
        lines.append("columns:")
        lines.extend(f"  {name}: {_q(desc)}" for name, desc in columns.items())
    return "\n".join(lines) + "\n"


def csv_bytes(header: list[str], rows: list[list[object]]) -> bytes:
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return buf.getvalue().encode("utf-8")


def normalize_zip(data: bytes) -> bytes:
    """Переписывает zip (xlsx/docx) с фиксированными временными метками — для побайтной воспроизводимости."""
    src = zipfile.ZipFile(io.BytesIO(data))
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as dst:
        for info in src.infolist():
            content = src.read(info.filename)
            if info.filename == "docProps/core.xml":
                content = re.sub(
                    rb"(<dcterms:(created|modified)[^>]*>)[^<]*(</dcterms:\2>)",
                    rb"\g<1>2026-11-04T00:00:00Z\g<3>",
                    content,
                )
            zi = zipfile.ZipInfo(info.filename, date_time=ZIP_DT)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            dst.writestr(zi, content)
    return out.getvalue()


class Out:
    """Файлы собираются в памяти (путь относительно evals/briefs → байты), потом пишутся или сверяются."""

    def __init__(self) -> None:
        self.files: dict[str, bytes] = {}

    def text(self, rel: str, text: str) -> None:
        if not text.endswith("\n"):
            text += "\n"
        self.files[rel] = text.encode("utf-8")

    def raw(self, rel: str, data: bytes) -> None:
        self.files[rel] = data


def pick(rng: np.random.Generator, items: list[str], p: list[float] | None = None) -> str:
    idx = int(rng.choice(len(items), p=p))
    return items[idx]


